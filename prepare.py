"""Build the Python training corpus from codeparrot-clean shards (JSON lines, .json.gz).

1. filter files (size, line length, alphabetic fraction, autogenerated, tests/setup boilerplate)
2. strip leading license/copyright comment blocks
3. train a 16k byte-level BPE on a sample
4. tokenize everything into data/train.bin + data/val.bin (uint16, files separated by EOT)
"""
import argparse
import glob
import gzip
import json
import os
import random
import re

import numpy as np

from ncm.bpe import CodeTokenizer, train_bpe

LICENSE_RE = re.compile(r"(licen[cs]e|copyright|\(c\))", re.I)


def strip_license_header(text):
    lines = text.split("\n")
    i = 0
    while i < len(lines) and (lines[i].startswith("#") or not lines[i].strip()):
        i += 1
    header = "\n".join(lines[:i])
    if i >= 3 and LICENSE_RE.search(header):
        keep = [l for l in lines[:i] if l.startswith("#!") or "coding" in l[:30]]
        return "\n".join(keep + lines[i:]).lstrip("\n")
    return text


def keep(rec):
    if rec.get("autogenerated") in (True, "True", "true"):
        return False
    c = rec["content"]
    if not (200 <= len(c) <= 100_000):
        return False
    if float(rec.get("line_max", 0)) > 200 or float(rec.get("line_mean", 0)) > 80:
        return False
    if float(rec.get("alpha_frac", 1)) < 0.3:
        return False
    name = os.path.basename(rec.get("path", ""))
    if name in ("setup.py", "__init__.py", "conftest.py") or "migrations/" in rec.get("path", ""):
        return False
    return True


def iter_files(paths):
    for p in paths:
        with gzip.open(p, "rt", encoding="utf-8") as f:
            for line in f:
                rec = json.loads(line)
                if keep(rec):
                    yield strip_license_header(rec["content"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="raw/*.json.gz")
    ap.add_argument("--out", default="data")
    ap.add_argument("--vocab", type=int, default=16384)
    ap.add_argument("--bpe-sample", type=int, default=60_000, help="files used to train the BPE")
    ap.add_argument("--val-files", type=int, default=2000)
    args = ap.parse_args()

    os.makedirs(args.out, exist_ok=True)
    paths = sorted(glob.glob(args.raw))
    bpe_path = os.path.join(args.out, "bpe.json")

    if not os.path.exists(bpe_path):
        sample, rng = [], random.Random(0)
        for i, text in enumerate(iter_files(paths[:1])):
            if rng.random() < 0.5:
                sample.append(text)
            if len(sample) >= args.bpe_sample:
                break
        print(f"training BPE on {len(sample)} files ...", flush=True)
        train_bpe(sample, bpe_path, args.vocab)
    tok = CodeTokenizer(bpe_path)
    assert tok.vocab_size <= 65536

    outs = {s: open(os.path.join(args.out, f"{s}.bin"), "wb") for s in ("train", "val")}
    counts = {"train": 0, "val": 0}
    n_files, batch = 0, []

    def flush():
        split = "val" if n_files <= args.val_files else "train"
        ids = []
        for seq in tok.encode_batch(batch):
            ids.extend(seq)
            ids.append(tok.eot_token)
        np.asarray(ids, dtype=np.uint16).tofile(outs[split])
        counts[split] += len(ids)

    for text in iter_files(paths):
        batch.append(text)
        n_files += 1
        if len(batch) == 1000 or n_files == args.val_files:
            flush()
            batch = []
            if n_files % 50_000 == 0:
                print(f"{n_files:,} files  train {counts['train'] / 1e6:.0f}M tokens", flush=True)
    if batch:
        flush()
    for f in outs.values():
        f.close()
    print(f"done: {n_files:,} files, train {counts['train']:,} tokens, val {counts['val']:,} tokens")


if __name__ == "__main__":
    main()
